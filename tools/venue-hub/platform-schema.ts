import type { PGlite } from '@electric-sql/pglite';
import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';

// Compatibility layer for running the versioned Supabase migrations on an
// embedded PostgreSQL (PGlite). Shared by the database tests and by the venue
// hub, so the hub executes exactly the schema, RLS and RPCs that CI replays.
// Only the Supabase-owned Auth/Storage/Vault/pg_cron surfaces are emulated; the
// emulation never validates GoTrue, PostgREST, Storage transport or Vault encryption.
export const PLATFORM_SHIM_SQL = `
    create role anon nologin;
    create role authenticated nologin;
    create role service_role nologin bypassrls;
    -- PGlite does not ship Supabase-hosted pg_cron. Emulate only the small contract
    -- used by migrations so the full schema can still be replayed in database tests.
    create schema cron;
    create table cron.job(
      jobid bigserial primary key,
      schedule text not null,
      command text not null,
      nodename text not null default 'localhost',
      nodeport integer not null default 5432,
      database text default current_database(),
      username text default current_user,
      active boolean not null default true,
      jobname text unique
    );
    -- pg_cron extension fixture: run history exists on hosted Supabase.
    -- Empty by default; never simulate successful scheduled runs.
    create table cron.job_run_details(
      jobid bigint,
      runid bigint generated by default as identity primary key,
      job_pid integer,
      database text,
      username text,
      command text,
      status text,
      return_message text,
      start_time timestamptz,
      end_time timestamptz
    );
    create function cron.schedule(p_jobname text,p_schedule text,p_command text) returns bigint
    language plpgsql as $$
    declare ref bigint;
    begin
      insert into cron.job(jobname,schedule,command,active)
      values(p_jobname,p_schedule,p_command,true)
      on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command,active=true
      returning jobid into ref;
      return ref;
    end $$;
    create function cron.unschedule(p_jobname text) returns boolean
    language plpgsql as $$
    begin
      delete from cron.job where jobname=p_jobname;
      return found;
    end $$;
    -- Match the additional pg_cron overloads installed on Supabase:
    -- unschedule accepts a job ID and unnamed schedules use two arguments.
    create function cron.unschedule(p_jobid bigint) returns boolean
    language plpgsql as $$
    begin
      delete from cron.job where jobid=p_jobid;
      return found;
    end $$;
    create function cron.schedule(p_schedule text,p_command text) returns bigint
    language plpgsql as $$
    declare ref bigint;
    begin
      insert into cron.job(schedule,command,active)
      values(p_schedule,p_command,true)
      returning jobid into ref;
      return ref;
    end $$;
    -- Supabase Vault is hosted; PGlite cannot load its encrypted storage.
    -- This fixture only reproduces SQL shape and create/read behavior in the
    -- disposable database. It does NOT validate encryption, Vault policies
    -- or production secret delivery. Never insert live credentials here.
    create schema if not exists vault;
    create table vault.secrets(
      id uuid primary key default gen_random_uuid(),
      name text unique,
      description text,
      secret text not null,
      key_id uuid
    );
    create view vault.decrypted_secrets as
      select id,name,description,secret,secret as decrypted_secret,key_id
      from vault.secrets;
    create function vault.create_secret(
      new_secret text,
      new_name text default null,
      new_description text default null,
      new_key_id uuid default null
    ) returns uuid
    language plpgsql
    security invoker
    set search_path=''
    as $$
    declare new_id uuid;
    begin
      insert into vault.secrets(name,description,secret,key_id)
      values(new_name,new_description,new_secret,new_key_id)
      returning id into new_id;
      return new_id;
    end $$;
    revoke all on schema vault from public,anon,authenticated;
    revoke all on vault.secrets,vault.decrypted_secrets from public,anon,authenticated;
    revoke all on function vault.create_secret(text,text,text,uuid)
      from public,anon,authenticated;
    create schema supabase_migrations;
    create table supabase_migrations.schema_migrations(
      version text primary key,
      name text not null,
      statements text[] not null default '{}'::text[]
    );
    -- Reproduce the hosted platform's schema-local API grants, not just PostgreSQL defaults.
    alter default privileges in schema public grant execute on functions to anon,authenticated,service_role;
    alter default privileges in schema public grant all on tables to anon,authenticated,service_role;
    alter default privileges in schema public grant all on sequences to anon,authenticated,service_role;
    -- Storage metadata fixture: object transport and its gateway are verified separately on Supabase.
    create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,metadata jsonb);
    alter table storage.objects enable row level security;
    grant usage on schema storage to anon,authenticated,service_role;
    grant select on storage.objects to anon,authenticated;
    create schema auth;
    create table auth.users(id uuid primary key, email text);
    create table auth.sessions(id uuid primary key, user_id uuid not null references auth.users(id));
    create function auth.jwt() returns jsonb language sql stable as
      $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    create function auth.uid() returns uuid language sql stable as
      $$ select (auth.jwt()->>'sub')::uuid $$;
    grant usage on schema auth to anon,authenticated,service_role;
    grant execute on all functions in schema auth to anon,authenticated,service_role;
  `;

export async function installPlatformShim(db: PGlite) {
  await db.exec(PLATFORM_SHIM_SQL);
}

export async function migrationNames(
  directory = 'supabase/migrations',
  through = Number.POSITIVE_INFINITY,
) {
  return (await readdir(directory))
    .filter((name) => name.endsWith('.sql'))
    .sort()
    .slice(0, through);
}

// Applies every migration not yet recorded in supabase_migrations.schema_migrations.
// Each migration and its history row are committed together, so an interrupted
// bootstrap resumes from the first unrecorded file instead of re-running SQL.
export async function replayMigrations(
  db: PGlite,
  options: { directory?: string; through?: number; transactional?: boolean } = {},
) {
  const directory = options.directory ?? 'supabase/migrations';
  const names = await migrationNames(directory, options.through);
  const done = new Set(
    (
      await db.query<{ version: string }>(
        'select version from supabase_migrations.schema_migrations',
      )
    ).rows.map((row) => row.version),
  );
  let applied = 0;
  for (const name of names) {
    const match = /^(\d+)_([^.]*)\.sql$/.exec(name);
    if (match && done.has(match[1]!)) continue;
    let sql = await readFile(join(directory, name), 'utf8');
    // pg_cron itself is host-provided on Supabase; the contract above is used in PGlite.
    sql = sql.replace(/^create extension if not exists pg_cron;\s*$/gim, '');
    // Continuity rehearsal tables are created by the versioned recovery migration.
    // Never inject out-of-band tables into a clean-install replay fixture.
    try {
      const run = async (tx: Pick<PGlite, 'exec' | 'query'>) => {
        await tx.exec(sql);
        if (match)
          await tx.query(
            `insert into supabase_migrations.schema_migrations(version,name,statements) values($1,$2,$3)`,
            [match[1], match[2], [sql]],
          );
      };
      if (options.transactional) await db.transaction(run);
      else await run(db);
      applied += 1;
    } catch (error) {
      throw new Error(`Migration ${name} failed`, { cause: error });
    }
  }
  return { total: names.length, applied };
}
