import { readFile } from 'node:fs/promises';
import { masterSectionCount, specificationProblems } from './requirements-spec.mjs';
const document = JSON.parse(await readFile('docs/REQUIREMENTS.json', 'utf8'));
const master = await readFile('MASTER_PROMPT_PLATEFORM_COMMERCIALE.md', 'utf8');
const problems = specificationProblems(document, master);
if (problems.length) throw new Error(problems.join('\n'));
const incomplete = document.sections.filter((entry) => entry.status !== 'verified');
console.log(`${masterSectionCount - incomplete.length}/${masterSectionCount} sezioni verificate.`);
for (const entry of incomplete) console.log(`§${entry.section} ${entry.status}: ${entry.title}`);
if (incomplete.length) process.exitCode = 1;
