import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import { readFile, readdir } from 'node:fs/promises';

// Real PostgreSQL engine in WASM. Only the Supabase-owned Auth schema is a test fixture.
// These tests do not claim to exercise GoTrue, PostgREST, Storage, or Realtime.
export async function database(through = Number.POSITIVE_INFINITY) {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(`
    create role anon nologin;
    create role authenticated nologin;
    create role service_role nologin bypassrls;
    -- PGlite does not ship Supabase-hosted pg_cron. Emulate only the small contract
    -- used by migrations so the full schema can still be replayed in database tests.
    create schema cron;
    create table cron.job(
      jobid bigserial primary key,
      schedule text not null,
      command text not null,
      nodename text not null default 'localhost',
      nodeport integer not null default 5432,
      database text default current_database(),
      username text default current_user,
      active boolean not null default true,
      jobname text unique
    );
    -- pg_cron extension fixture: run history exists on hosted Supabase.
    -- Empty by default; never simulate successful scheduled runs.
    create table cron.job_run_details(
      jobid bigint,
      runid bigint generated by default as identity primary key,
      job_pid integer,
      database text,
      username text,
      command text,
      status text,
      return_message text,
      start_time timestamptz,
      end_time timestamptz
    );
    create function cron.schedule(p_jobname text,p_schedule text,p_command text) returns bigint
    language plpgsql as $$
    declare ref bigint;
    begin
      insert into cron.job(jobname,schedule,command,active)
      values(p_jobname,p_schedule,p_command,true)
      on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command,active=true
      returning jobid into ref;
      return ref;
    end $$;
    create function cron.unschedule(p_jobname text) returns boolean
    language plpgsql as $$
    begin
      delete from cron.job where jobname=p_jobname;
      return found;
    end $$;
    -- Match the additional pg_cron overloads installed on Supabase:
    -- unschedule accepts a job ID and unnamed schedules use two arguments.
    create function cron.unschedule(p_jobid bigint) returns boolean
    language plpgsql as $$
    begin
      delete from cron.job where jobid=p_jobid;
      return found;
    end $$;
    create function cron.schedule(p_schedule text,p_command text) returns bigint
    language plpgsql as $$
    declare ref bigint;
    begin
      insert into cron.job(schedule,command,active)
      values(p_schedule,p_command,true)
      returning jobid into ref;
      return ref;
    end $$;
    -- Supabase Vault is hosted; PGlite cannot load its encrypted storage.
    -- This fixture only reproduces SQL shape and create/read behavior in the
    -- disposable database. It does NOT validate encryption, Vault policies
    -- or production secret delivery. Never insert live credentials here.
    create schema if not exists vault;
    create table vault.secrets(
      id uuid primary key default gen_random_uuid(),
      name text unique,
      description text,
      secret text not null,
      key_id uuid
    );
    create view vault.decrypted_secrets as
      select id,name,description,secret,secret as decrypted_secret,key_id
      from vault.secrets;
    create function vault.create_secret(
      new_secret text,
      new_name text default null,
      new_description text default null,
      new_key_id uuid default null
    ) returns uuid
    language plpgsql
    security invoker
    set search_path=''
    as $$
    declare new_id uuid;
    begin
      insert into vault.secrets(name,description,secret,key_id)
      values(new_name,new_description,new_secret,new_key_id)
      returning id into new_id;
      return new_id;
    end $$;
    revoke all on schema vault from public,anon,authenticated;
    revoke all on vault.secrets,vault.decrypted_secrets from public,anon,authenticated;
    revoke all on function vault.create_secret(text,text,text,uuid)
      from public,anon,authenticated;
    create schema supabase_migrations;
    create table supabase_migrations.schema_migrations(
      version text primary key,
      name text not null,
      statements text[] not null default '{}'::text[]
    );
    -- Reproduce the hosted platform's schema-local API grants, not just PostgreSQL defaults.
    alter default privileges in schema public grant execute on functions to anon,authenticated,service_role;
    alter default privileges in schema public grant all on tables to anon,authenticated,service_role;
    alter default privileges in schema public grant all on sequences to anon,authenticated,service_role;
    -- Storage metadata fixture: object transport and its gateway are verified separately on Supabase.
    create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,metadata jsonb);
    alter table storage.objects enable row level security;
    grant usage on schema storage to anon,authenticated,service_role;
    grant select on storage.objects to anon,authenticated;
    create schema auth;
    create table auth.users(id uuid primary key, email text);
    create table auth.sessions(id uuid primary key, user_id uuid not null references auth.users(id));
    create function auth.jwt() returns jsonb language sql stable as
      $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
    create function auth.uid() returns uuid language sql stable as
      $$ select (auth.jwt()->>'sub')::uuid $$;
    grant usage on schema auth to anon,authenticated,service_role;
    grant execute on all functions in schema auth to anon,authenticated,service_role;
  `);
  const names = (await readdir('supabase/migrations'))
    .filter((name) => name.endsWith('.sql'))
    .sort()
    .slice(0, through);
  for (const name of names) {
    try {
      let sql = await readFile(`supabase/migrations/${name}`, 'utf8');
      // pg_cron itself is host-provided on Supabase; the contract above is used in PGlite.
      sql = sql.replace(/^create extension if not exists pg_cron;\s*$/gim, '');
      // Historical drift, verified against the live Development catalog:
      // these seven private tables exist on the hosted database, but none of
      // the 456 recorded migrations contains their CREATE TABLE statements.
      // Provide the actual hosted table shapes only to the isolated PGlite
      // replay, immediately before their first recorded reference.
      // This is NOT a migration-history repair: clean-environment deployment
      // remains blocked until the out-of-band schema is properly reconciled.
      if (name === '20261006100248_step13_rehearsal_private_rls_hardening.sql') {
        await db.exec(`
          create table private.continuity_rehearsal_blob (
            snapshot_id uuid primary key,
            row_count bigint not null,
            table_count integer not null,
            plaintext_sha256 text not null,
            cipher bytea not null,
            created_at timestamptz not null default now()
          );
          create table private.continuity_rehearsal_key (
            id boolean primary key default true check (id),
            key_material text not null default encode(extensions.gen_random_bytes(32), 'hex'),
            created_at timestamptz not null default now()
          );
          create table private.continuity_rehearsal_snapshot_manifest (
            snapshot_id uuid primary key,
            created_at timestamptz not null default now(),
            migration_count integer not null,
            migration_latest_version text not null,
            migration_aggregate_sha256 text not null,
            auth_user_count bigint not null,
            durable_private_row_count bigint not null,
            durable_private_sha256 text not null,
            table_count integer not null,
            row_count bigint not null,
            storage_bucket_count bigint not null,
            storage_object_count bigint not null,
            status text not null default 'FROZEN'
          );
          create table private.continuity_rehearsal_snapshot_rows (
            snapshot_id uuid not null references
              private.continuity_rehearsal_snapshot_manifest(snapshot_id) on delete cascade,
            schema_name text not null,
            table_name text not null,
            row_no bigint not null,
            row_data jsonb not null,
            primary key (snapshot_id, schema_name, table_name, row_no)
          );
          create table private.continuity_rehearsal_snapshot_tables (
            snapshot_id uuid not null,
            schema_name text not null,
            table_name text not null,
            row_count bigint not null,
            data_sha256 text not null,
            insert_columns text[] not null,
            has_identity_always boolean not null,
            generated_columns text[] not null,
            primary key (snapshot_id, schema_name, table_name)
          );
          create table private.continuity_rehearsal_transfer_chunks (
            snapshot_id uuid not null,
            chunk_no integer not null,
            row_count integer not null,
            plaintext_sha256 text not null,
            ciphertext bytea not null,
            created_at timestamptz not null default now(),
            primary key (snapshot_id, chunk_no)
          );
          create table private.continuity_rehearsal_transfer_key (
            snapshot_id uuid primary key,
            encryption_key text not null,
            created_at timestamptz not null default now()
          );
        `);
      }
      await db.exec(sql);
      const match = /^(\d+)_([^.]*)\.sql$/.exec(name);
      if (match)
        await db.query(
          `insert into supabase_migrations.schema_migrations(version,name,statements) values($1,$2,$3)`,
          [match[1], match[2], [sql]],
        );
    } catch (error) {
      if (name === '20261008163112_step11_public_rpc_permission_manifest.sql') {
        const diagnosis = await db.query<{
          identity: string;
          present: boolean;
          security_definer: boolean | null;
          configuration: string[] | null;
        }>(`
          select name.identity, p.oid is not null present, p.prosecdef security_definer,
                 p.proconfig configuration
          from (values ('public.get_public_menu_index(uuid)'),
                       ('public.get_public_navigation(uuid)'),
                       ('public.get_public_page_metadata(text,uuid)'),
                       ('public.get_public_sitemap_entries()')) name(identity)
          left join pg_catalog.pg_proc p
             on p.oid=pg_catalog.to_regprocedure(name.identity)
        `);
        console.error('STEP11_PUBLIC_RPC_DIAGNOSTIC', JSON.stringify(diagnosis.rows));
      }
      await db.close();
      throw new Error(`Migration ${name} failed`, { cause: error });
    }
  }
  return db;
}

export async function identity(db: PGlite, user: string, aal = 'aal2') {
  await db.query(`select set_config('request.jwt.claims', $1, false)`, [
    JSON.stringify({
      sub: user,
      aal,
      iat: Math.floor(Date.now() / 1000),
      session_id: sessionId(user),
      amr: [{ method: 'password', timestamp: Math.floor(Date.now() / 1000) }],
    }),
  ]);
  await db.exec('set role authenticated');
}

export function sessionId(user: string) {
  return user.replace(/^2/, '3');
}

