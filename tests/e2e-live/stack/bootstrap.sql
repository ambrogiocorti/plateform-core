-- Disposable local stack only (PostgreSQL 16 + GoTrue + PostgREST).
-- Reproduces the Supabase-owned roles/schemas the migrations rely on.
-- pg_cron, Vault and (without Docker) Storage are SQL-shape fixtures (same contract as
-- tests/database/harness.ts): they do NOT validate scheduling, encryption or object transport.
create role anon nologin noinherit;
create role authenticated nologin noinherit;
create role service_role nologin noinherit bypassrls;
create role authenticator login noinherit password 'local-e2e-authenticator';
grant anon, authenticated, service_role to authenticator;
create role supabase_auth_admin login createrole noinherit password 'local-e2e-auth-admin';
alter role supabase_auth_admin set search_path = auth;
-- per-database --
create schema auth authorization supabase_auth_admin;
do $$ begin execute format('grant create on database %I to supabase_auth_admin', current_database()); end $$;
create schema extensions;
create extension pgcrypto with schema extensions;
grant usage on schema extensions to anon, authenticated, service_role;
create schema cron;
create table cron.job(
  jobid bigserial primary key, schedule text not null, command text not null,
  nodename text not null default 'localhost', nodeport integer not null default 5432,
  database text default current_database(), username text default current_user,
  active boolean not null default true, jobname text unique);
create table cron.job_run_details(
  jobid bigint, runid bigint generated by default as identity primary key, job_pid integer,
  database text, username text, command text, status text, return_message text,
  start_time timestamptz, end_time timestamptz);
create function cron.schedule(p_jobname text,p_schedule text,p_command text) returns bigint
language plpgsql as $$ declare ref bigint; begin
  insert into cron.job(jobname,schedule,command,active) values(p_jobname,p_schedule,p_command,true)
  on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command,active=true
  returning jobid into ref; return ref; end $$;
create function cron.unschedule(p_jobname text) returns boolean
language plpgsql as $$ begin delete from cron.job where jobname=p_jobname; return found; end $$;
create function cron.unschedule(p_jobid bigint) returns boolean
language plpgsql as $$ begin delete from cron.job where jobid=p_jobid; return found; end $$;
create function cron.schedule(p_schedule text,p_command text) returns bigint
language plpgsql as $$ declare ref bigint; begin
  insert into cron.job(schedule,command,active) values(p_schedule,p_command,true) returning jobid into ref;
  return ref; end $$;
create schema vault;
create table vault.secrets(id uuid primary key default gen_random_uuid(), name text unique,
  description text, secret text not null, key_id uuid);
create view vault.decrypted_secrets as
  select id,name,description,secret,secret as decrypted_secret,key_id from vault.secrets;
create function vault.create_secret(new_secret text,new_name text default null,
  new_description text default null,new_key_id uuid default null) returns uuid
language plpgsql security invoker set search_path='' as $$ declare new_id uuid; begin
  insert into vault.secrets(name,description,secret,key_id) values(new_name,new_description,new_secret,new_key_id)
  returning id into new_id; return new_id; end $$;
revoke all on schema vault from public,anon,authenticated;
revoke all on vault.secrets,vault.decrypted_secrets from public,anon,authenticated;
create schema supabase_migrations;
create table supabase_migrations.schema_migrations(version text primary key, name text not null,
  statements text[] not null default '{}'::text[]);
alter default privileges in schema public grant execute on functions to anon,authenticated,service_role;
alter default privileges in schema public grant all on tables to anon,authenticated,service_role;
alter default privileges in schema public grant all on sequences to anon,authenticated,service_role;
grant usage on schema public to anon, authenticated, service_role;
-- storage stub -- (dropped when the stack runs the real storage-api, which owns this schema)
