-- Supabase host fixture for disposable migration replays (PGlite and local PostgreSQL 16).
-- It reproduces only the platform-owned objects migrations depend on: API roles, pg_cron
-- and Vault SQL shape, schema_migrations, Storage metadata and the Auth helper functions.
-- It does NOT emulate GoTrue, PostgREST, Storage transport, Realtime or Vault encryption.
-- Roles are cluster-wide on a real server, so their creation is idempotent.
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
end $$;
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
end $$;
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;
-- PGlite does not ship Supabase-hosted pg_cron. Emulate only the small contract
-- used by migrations so the full schema can still be replayed in database tests.
create schema cron;
create table cron.job(
  jobid bigserial primary key,
  schedule text not null,
  command text not null,
  nodename text not null default 'localhost',
  nodeport integer not null default 5432,
  database text default current_database(),
  username text default current_user,
  active boolean not null default true,
  jobname text unique
);
-- pg_cron extension fixture: run history exists on hosted Supabase.
-- Empty by default; never simulate successful scheduled runs.
create table cron.job_run_details(
  jobid bigint,
  runid bigint generated by default as identity primary key,
  job_pid integer,
  database text,
  username text,
  command text,
  status text,
  return_message text,
  start_time timestamptz,
  end_time timestamptz
);
create function cron.schedule(p_jobname text,p_schedule text,p_command text) returns bigint
language plpgsql as $$
declare ref bigint;
begin
  insert into cron.job(jobname,schedule,command,active)
  values(p_jobname,p_schedule,p_command,true)
  on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command,active=true
  returning jobid into ref;
  return ref;
end $$;
create function cron.unschedule(p_jobname text) returns boolean
language plpgsql as $$
begin
  delete from cron.job where jobname=p_jobname;
  return found;
end $$;
-- Match the additional pg_cron overloads installed on Supabase:
-- unschedule accepts a job ID and unnamed schedules use two arguments.
create function cron.unschedule(p_jobid bigint) returns boolean
language plpgsql as $$
begin
  delete from cron.job where jobid=p_jobid;
  return found;
end $$;
create function cron.schedule(p_schedule text,p_command text) returns bigint
language plpgsql as $$
declare ref bigint;
begin
  insert into cron.job(schedule,command,active)
  values(p_schedule,p_command,true)
  returning jobid into ref;
  return ref;
end $$;
-- Supabase Vault is hosted; PGlite cannot load its encrypted storage.
-- This fixture only reproduces SQL shape and create/read behavior in the
-- disposable database. It does NOT validate encryption, Vault policies
-- or production secret delivery. Never insert live credentials here.
create schema if not exists vault;
create table vault.secrets(
  id uuid primary key default gen_random_uuid(),
  name text unique,
  description text,
  secret text not null,
  key_id uuid
);
create view vault.decrypted_secrets as
  select id,name,description,secret,secret as decrypted_secret,key_id
  from vault.secrets;
create function vault.create_secret(
  new_secret text,
  new_name text default null,
  new_description text default null,
  new_key_id uuid default null
) returns uuid
language plpgsql
security invoker
set search_path=''
as $$
declare new_id uuid;
begin
  insert into vault.secrets(name,description,secret,key_id)
  values(new_name,new_description,new_secret,new_key_id)
  returning id into new_id;
  return new_id;
end $$;
revoke all on schema vault from public,anon,authenticated;
revoke all on vault.secrets,vault.decrypted_secrets from public,anon,authenticated;
revoke all on function vault.create_secret(text,text,text,uuid)
  from public,anon,authenticated;
