-- Disposable local PostgreSQL 16 fixture reproducing the Supabase platform
-- objects that Plateform migrations reference. It is NOT GoTrue, PostgREST,
-- Storage API or Realtime: it reproduces only the SQL contract those services
-- rely on (roles, JWT claim GUCs, auth/storage tables, default API grants).
-- Never point this script at a shared, staging or production database.
do $$ begin
  if current_database() !~ '^plateform_security_' then
    raise exception 'REFUSED: fixture only runs on a disposable plateform_security_* database';
  end if;
end $$;

do $$ begin
  if not exists(select 1 from pg_roles where rolname='anon') then create role anon nologin noinherit; end if;
  if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin noinherit; end if;
  if not exists(select 1 from pg_roles where rolname='service_role') then create role service_role nologin noinherit bypassrls; end if;
  if not exists(select 1 from pg_roles where rolname='authenticator') then create role authenticator login noinherit; end if;
end $$;
grant anon,authenticated,service_role to authenticator;

create schema if not exists extensions;
grant usage on schema extensions to anon,authenticated,service_role;

-- pg_cron contract (hosted extension on Supabase).
create schema cron;
create table cron.job(jobid bigserial primary key,schedule text not null,command text not null,
  nodename text not null default 'localhost',nodeport integer not null default 5432,
  database text default current_database(),username text default current_user,
  active boolean not null default true,jobname text unique);
create table cron.job_run_details(jobid bigint,runid bigint generated by default as identity primary key,
  job_pid integer,database text,username text,command text,status text,return_message text,
  start_time timestamptz,end_time timestamptz);
create function cron.schedule(p_jobname text,p_schedule text,p_command text) returns bigint language plpgsql as $$
declare ref bigint; begin
  insert into cron.job(jobname,schedule,command,active) values(p_jobname,p_schedule,p_command,true)
  on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command,active=true returning jobid into ref;
  return ref; end $$;
create function cron.schedule(p_schedule text,p_command text) returns bigint language plpgsql as $$
declare ref bigint; begin insert into cron.job(schedule,command) values(p_schedule,p_command) returning jobid into ref; return ref; end $$;
create function cron.unschedule(p_jobname text) returns boolean language plpgsql as $$
begin delete from cron.job where jobname=p_jobname; return found; end $$;
create function cron.unschedule(p_jobid bigint) returns boolean language plpgsql as $$
begin delete from cron.job where jobid=p_jobid; return found; end $$;
revoke all on schema cron from public;

