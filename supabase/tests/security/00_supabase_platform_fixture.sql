-- Vault contract (no encryption is validated here).
create schema vault;
create table vault.secrets(id uuid primary key default gen_random_uuid(),name text unique,description text,secret text not null,key_id uuid);
create view vault.decrypted_secrets as select id,name,description,secret,secret as decrypted_secret,key_id from vault.secrets;
create function vault.create_secret(new_secret text,new_name text default null,new_description text default null,new_key_id uuid default null)
returns uuid language plpgsql set search_path='' as $$
declare new_id uuid; begin insert into vault.secrets(name,description,secret,key_id) values(new_name,new_description,new_secret,new_key_id) returning id into new_id; return new_id; end $$;
revoke all on schema vault from public,anon,authenticated;

