-- Auth: same claim lookup GoTrue/PostgREST use (request.jwt.claims GUC).
create schema auth;
create table auth.users(id uuid primary key,email text,phone text,raw_app_meta_data jsonb default '{}',raw_user_meta_data jsonb default '{}',
  created_at timestamptz default now(),last_sign_in_at timestamptz,banned_until timestamptz,deleted_at timestamptz);
create table auth.sessions(id uuid primary key,user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz default now(),updated_at timestamptz default now(),aal text,not_after timestamptz);
create table auth.mfa_factors(id uuid primary key default gen_random_uuid(),user_id uuid not null references auth.users(id) on delete cascade,
  friendly_name text,factor_type text not null default 'totp',status text not null default 'verified',created_at timestamptz default now(),updated_at timestamptz default now());
create table auth.audit_log_entries(instance_id uuid,id uuid primary key default gen_random_uuid(),payload json,created_at timestamptz default now(),ip_address varchar(64) default '');
create function auth.jwt() returns jsonb language sql stable as
  $$ select coalesce(nullif(current_setting('request.jwt.claim',true),''),nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
create function auth.uid() returns uuid language sql stable as
  $$ select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),(auth.jwt()->>'sub'))::uuid $$;
create function auth.role() returns text language sql stable as
  $$ select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),(auth.jwt()->>'role'))::text $$;
create function auth.email() returns text language sql stable as $$ select auth.jwt()->>'email' $$;
grant usage on schema auth to anon,authenticated,service_role;
grant execute on function auth.jwt(),auth.uid(),auth.role(),auth.email() to anon,authenticated,service_role;

-- Storage metadata contract used by the Storage API for RLS decisions.
create schema storage;
create table storage.buckets(id text primary key,name text not null,owner uuid,public boolean default false,
  file_size_limit bigint,allowed_mime_types text[],created_at timestamptz default now(),updated_at timestamptz default now());
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,
  owner uuid,owner_id text,metadata jsonb,path_tokens text[] generated always as (string_to_array(name,'/')) stored,
  created_at timestamptz default now(),updated_at timestamptz default now(),last_accessed_at timestamptz default now(),version text);
create function storage.foldername(name text) returns text[] language sql immutable as
  $$ select (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1] $$;
create function storage.filename(name text) returns text language sql immutable as
  $$ select (string_to_array(name,'/'))[array_length(string_to_array(name,'/'),1)] $$;
alter table storage.objects enable row level security;
alter table storage.buckets enable row level security;
grant usage on schema storage to anon,authenticated,service_role;
grant all on storage.objects,storage.buckets to anon,authenticated,service_role;
grant execute on all functions in schema storage to anon,authenticated,service_role;

-- Hosted Supabase grants API roles on new public objects by default.
alter default privileges in schema public grant execute on functions to anon,authenticated,service_role;
alter default privileges in schema public grant all on tables to anon,authenticated,service_role;
alter default privileges in schema public grant all on sequences to anon,authenticated,service_role;
grant usage on schema public to anon,authenticated,service_role;
